"""Trains several models to predict final exam scores and tracks each as an MLflow run.
Run: MLFLOW_TRACKING_URI=http://localhost:5000 python train.py"""
import mlflow
import mlflow.sklearn
from sklearn.dummy import DummyRegressor
from sklearn.ensemble import RandomForestRegressor
from sklearn.linear_model import Ridge
from sklearn.metrics import mean_squared_error, r2_score
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeRegressor

from data import FEATURES, TARGET, make_students

SEED = 42
DATA_CARD = """# Data card: synthetic students (synthetic-v1)

- Source: generated by data.py with make_students(n=600, seed=42). Invented data; no real student is described.
- Rows: 600 (450 for training, 150 held out for testing, split with random_state=42).
- Features: study_hours (0-20 per week), attendance (50-100 %), previous_score (0-100), sleep_hours (4-10).
- Target: final_score (0-100), from a made-up formula with random noise and diminishing returns for study hours.
- Limits: real exam results depend on much more; do not use these models for decisions about real students.
"""

df = make_students(n=600, seed=SEED)
X_train, X_test, y_train, y_test = train_test_split(df[FEATURES], df[TARGET], test_size=0.25, random_state=SEED)

MODELS = {
    "baseline": DummyRegressor(strategy="mean"),                  # what "no model" scores
    "ridge": Ridge(alpha=1.0),
    "decision_tree": DecisionTreeRegressor(max_depth=4, random_state=SEED),
    "random_forest": RandomForestRegressor(n_estimators=100, max_depth=6, random_state=SEED),
}

mlflow.set_experiment("student-performance")
for name, model in MODELS.items():
    with mlflow.start_run(run_name=name):
        model.fit(X_train, y_train)
        predicted = model.predict(X_test)          # measured on data the model has never seen
        mlflow.log_params({"model": name, "seed": SEED, **model.get_params()})
        mlflow.log_metrics({"rmse": float(mean_squared_error(y_test, predicted) ** 0.5), "r2": float(r2_score(y_test, predicted))})
        mlflow.set_tag("dataset", "synthetic-v1")
        mlflow.log_text(DATA_CARD, "data_card.md")
        # MLflow 3.18 saves scikit-learn models with skops, which refuses to load types it does not know.
        # Tree models store their nodes in sklearn.tree._tree.Tree; we created the file ourselves, so we
        # name that one type as trusted (never trust everything just to make a file load).
        trusted = ["sklearn.tree._tree.Tree"] if name in ("decision_tree", "random_forest") else None
        mlflow.sklearn.log_model(model, name="model", input_example=X_test.head(3), skops_trusted_types=trusted)
        print(f"{name:14} rmse {mean_squared_error(y_test, predicted) ** 0.5:.3f}")
